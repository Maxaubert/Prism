/**
 * Writes src/renderer/src/lib/folderIconSet.ts, the built-in folder icons
 * (owner, 2026-10-31: "the user can pick from a set of built in icons. at
 * least 300 different icons"): every Lucide icon, each one path `d` for
 * Prism's `Icon` primitive, its tags for the picker's search (at most 8, D15),
 * and its filled dots apart. `lucide-static` is a DEV dependency: only this
 * generated module ships, loaded on demand as its own chunk.
 *
 *   npm run icons:folders
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { iconToPaths } from '../lib/svgToPath.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const PKG = join(ROOT, 'node_modules', 'lucide-static')
const OUT = join(ROOT, 'src', 'renderer', 'src', 'lib', 'folderIconSet.ts')
const MAX_TAGS = 8

const version = JSON.parse(readFileSync(join(PKG, 'package.json'), 'utf8')).version
const nodes = JSON.parse(readFileSync(join(PKG, 'icon-nodes.json'), 'utf8'))
const tags = JSON.parse(readFileSync(join(PKG, 'tags.json'), 'utf8'))

const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
// Tags are words and short phrases; a comma never appears in one.
const clean = (t) => t.replace(/,/g, ' ').replace(/\s+/g, ' ').trim()

const rows = Object.keys(nodes)
  .sort()
  .map((name) => {
    const { d, fill } = iconToPaths(nodes[name])
    const words = [...new Set((tags[name] ?? []).map(clean).filter(Boolean))].slice(0, MAX_TAGS)
    const parts = [quote(name), quote(d), quote(words.join(','))]
    if (fill) parts.push(quote(fill))
    return `  [${parts.join(', ')}]`
  })

const src = `// GENERATED by tools/icons/folder-icons.mjs from lucide-static ${version}; do not hand-edit.
// Lucide icons (ISC, with an MIT part for those derived from Feather): see
// THIRD-PARTY-NOTICES.md. Loaded with a dynamic import, so this is its own
// chunk and never part of the launch bundle (lib/folderIconSetLoad.ts).

/** name, the stroked path, its tags joined by commas, and its filled dots. */
export type IconRow = readonly [name: string, d: string, tags: string, fill?: string]

export const LUCIDE_VERSION = '${version}'

export const LUCIDE: readonly IconRow[] = [
${rows.join(',\n')}
]
`
writeFileSync(OUT, src)
console.log(`wrote ${rows.length} icons to ${OUT} (${(src.length / 1024).toFixed(0)}KB)`)
